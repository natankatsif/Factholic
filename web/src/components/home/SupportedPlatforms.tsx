export type PlatformId = "youtube" | "shorts" | "link" | "tiktok" | "facebook" | "x";

export interface LinkPlatform {
  id: PlatformId;
  name: string;
  color: string;
  /** Иконка 14×14 — из экспорта дизайна */
  icon?: string;
  /** Иконка lucide — для плашек, которых нет в макете */
  lucide?: LucideIcon;
  /** Шарик-маскот blob.png вместо векторной иконки */
  isBlob?: boolean;
  /** Ошибка, если ссылка не подходит: «Это не похоже на ссылку TikTok» */
  invalidText?: string;
  /** Подсказка в поле ссылки */
  placeholder: string;
  /** Ссылка подходит этой платформе */
  matches: (link: string) => boolean;
  /** Ещё в разработке: проверку не запускаем, чудик из толпы говорит, что скоро */
  soon?: boolean;
}

function hostOf(link: string): string {
  try {
    const url = new URL(/^https?:\/\//i.test(link.trim()) ? link.trim() : `https://${link.trim()}`);
    return url.hostname.replace(/^(www|m|mobile|web)\./, "");
  } catch {
    return "";
  }
}

