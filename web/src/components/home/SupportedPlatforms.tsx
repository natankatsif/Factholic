/** Платформа ссылки: Shorts отличаем от обычного YouTube по пути /shorts/ */
export function platformOfLink(link: string): LinkPlatform | null {
  if (youtubeVideoId(link)) {
    return PLATFORMS.find((p) => p.id === (/\/shorts\//i.test(link) ? "shorts" : "youtube")) ?? null;
  }
  // своя платформа (TikTok, X…) важнее «просто ссылки»: та — для всего остального
  const special = PLATFORMS.find(
    (p) => p.id !== "youtube" && p.id !== "shorts" && p.id !== "link" && p.matches(link),
  );
  return special ?? PLATFORMS.find((p) => p.id === "link" && p.matches(link)) ?? null;
}

export function PlatformIcon({ platform, className }: { platform: LinkPlatform; className?: string }) {
  if (platform.isBlob || platform.id === "link") {
    return (
      <img
        src="/blob.png"
        alt=""
        draggable={false}
        className={`shrink-0 select-none object-contain rounded-full ${className ?? "h-4 w-4 sm:h-[18px] sm:w-[18px]"}`}
      />
    );
  }
  if (platform.lucide) {
    const Icon = platform.lucide;
    return <Icon aria-hidden strokeWidth={2.4} className={className} style={{ color: platform.color }} />;
  }
  return (
    <svg viewBox="0 0 14 14" fill="none" aria-hidden className={className}>
      <path d={platform.icon} fill={platform.color} />
    </svg>
  );
}

